#!/usr/bin/env python3
"""Generate lib/docs.zsh from the command descriptions in Helix's source.

Usage: utils/gen-docs.py /path/to/helix
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
helix = pathlib.Path(sys.argv[1])
source = (helix / "helix-term/src/commands.rs").read_text()
block = source[source.index("static_commands!(") :]
block = block[: block.index(");")]
docs = {}
for m in re.finditer(r'^\s+([A-Za-z_]+), "((?:[^"\\]|\\.)*)"', block, re.M):
    docs[m.group(1)] = m.group(2).encode().decode("unicode_escape")

implemented = set()
for path in (root / "lib").rglob("*.zsh"):
    implemented |= set(re.findall(r"^function _zhm_cmd_([A-Za-z0-9_]+)\(\)", path.read_text(), re.M))

# Commands that are specific to zshelix, or behave differently on a command
# line.
extra = {
    "accept_line": "Run the command line",
    "clear_screen": "Clear the screen",
    "history_prev": "Previous history entry",
    "history_next": "Next history entry",
    "repeat_last_insert": "Repeat the last insert",
    "eof_or_delete_char_forward": "Delete next char (exit the shell if the line is empty)",
    "eof_or_page_cursor_half_down": "Move page and cursor half down (exit the shell if the line is empty)",
    "insert_typed": "Insert the typed character",
    "insert_key_char": "Insert the character of a Ctrl or Alt key",
    "replay_end": "End replaying keys",
    "paste_bracketed_input": "Paste from the terminal",
    "repeat_insert_once": "Repeat the last insert once",
    "noop": "Do nothing",
    "extend_to_line": "Extend to line number",
    "select_textobject_inside_surrounding_pair": "Select inside surrounding pair",
    "select_textobject_around_surrounding_pair": "Select around surrounding pair",
    "select_textobject_inside_prev_pair": "Select inside previous pair",
    "select_textobject_inside_next_pair": "Select inside next pair",
    # Helix uses tree-sitter for these when available, and plain text
    # matching otherwise, which is what zshelix does.
    "select_textobject_inside_closest_surrounding_pair": "Select inside closest surrounding pair",
    "select_textobject_around_closest_surrounding_pair": "Select around closest surrounding pair",
}

def quote(s):
    return "'" + s.replace("'", "'\\''") + "'"

lines = [
    "# Command descriptions, generated by utils/gen-docs.py from Helix's source.",
    "",
    "typeset -gA _ZHM_DOCS=(",
]
missing = []
for name in sorted(implemented):
    if name.startswith("count_"):
        continue
    desc = extra.get(name) or docs.get(name)
    if desc is None:
        missing.append(name)
        continue
    lines.append(f"    {name} {quote(desc)}")
lines.append(")")
(root / "lib/docs.zsh").write_text("\n".join(lines) + "\n")
if missing:
    print("No description for:", ", ".join(missing), file=sys.stderr)
    sys.exit(1)
